# 值完全等于这些词的直接不查表（连子串匹配都不做）。
# 只放**确实零信息**的：平台明确说了「其他」或用了一个万能词。
# 「商户消费」在微信表里映射成空串，走的是表内空值分支，不靠这里。
_UNINFORMATIVE = frozenset({
    "其他", "其他交易", "交易", "消费", "无", "-", "/",
})


def _lookup(value: str, table: dict[str, str]) -> Optional[str]:
    """在一张映射表里查一个平台分类值。返回 None = 没查到 / 无信息量。

    查法是「长的 key 先试」：映射表里同时有「退款」和「已全额退款」时，
    必须让长的先命中，否则短词会抢先把长词吃掉。这个顺序固定下来，
    以后往表里加近义词条目时不会出现难排查的行为差异。
    """
    text = (value or "").strip()
    if not text or text in _UNINFORMATIVE:
        return None
    for key in sorted(table, key=len, reverse=True):
        if key and key in text:
            return table[key] or None      # 空串 = 这一格明确表示「无信息」
    return None


def from_alipay(value: str) -> Optional[str]:
    """支付宝「交易分类」→ 本地分类。"""
    return _lookup(value, ALIPAY_MAP)


def from_wechat(value: str) -> Optional[str]:
    """微信「交易类型」→ 本地分类。「商户消费」这类返回 None。"""
    return _lookup(value, WECHAT_MAP)


def from_bank(*values: str) -> Optional[str]:
    """银行的交易名称 / 渠道 / 附言 → 本地分类。

    多个值按传入顺序查，第一个命中的赢。
    调用方应按「信息量从大到小」传：交易名称 → 渠道 → 附言。
    """
    for value in values:
        hit = _lookup(value, BANK_MAP)
        if hit:
            return hit
    return None


def platform_category(source: str, value: str) -> Optional[str]:
    """按数据源选对应的表来查。source 取 Txn.source。"""
    if source == "alipay":
        return from_alipay(value)
    if source == "wechat":
        return from_wechat(value)
    if source in ("bank_ocr", "bank_pdf"):
        return from_bank(value)
    return None


def validate() -> list[str]:
    """自检：映射的值必须都是真实存在的分类。返回问题清单（空 = 通过）。

    存在的理由不是洁癖。往表里写一个不存在的分类名（比如手滑写了
    「生活服务」，而 CATEGORIES 里其实是「生活缴费」），代码不会报任何错，
    那笔交易只是安静地从所有分类统计里消失了 —— 月度报表总额少一块，
    而界面上看不出任何异常。靠肉眼看不出来的东西，就该让机器看。
    """
    problems: list[str] = []
    from .categorize import CATEGORIES
    known = set(CATEGORIES)
    for table_name, table in (("ALIPAY", ALIPAY_MAP), ("WECHAT", WECHAT_MAP),
                              ("BANK", BANK_MAP)):
        for key, value in table.items():
            if value and value not in known:
                problems.append(
                    f"{table_name}_MAP[{key!r}] = {value!r}，"
                    f"不在 CATEGORIES 里（这会让该分类的交易从统计中消失）"
                )
    return problems
