"""平台自带分类 → 本地分类体系的映射。

为什么优先用它，而不是靠关键词猜：
    支付宝的「交易分类」和微信的「交易类型」是平台**已经判好的**结果。
    同一笔「农行食堂 12.50」，我的规则要靠「食堂」两个字猜，
    平台直接就写了「餐饮美食」—— 而且它见过的商户比我多得多。
    拿现成的答案不用，等于自己重新做一遍更差的事。

优先级铁律（与项目既有约定一致，不许改）：
    人工指定 > 平台分类 > 关键词规则 > 原值
    人工指定仍然压过一切，任何路径都不许覆盖它。

三类平台值是**故意不参与判定**的：
    微信「商户消费」   —— 微信 90% 的流水都是这四个字，信息量为零。
    微信「二维码收款」 —— 同上，涵盖的场景太杂。
    支付宝「其他」      —— 平台自己都说了「其他」，等于没说。
    拿它们当分类依据，等于把所有消费压成一个类，比不做还糟。
    这类值一律返回 None，让流程落到关键词规则上。

两条硬约束（下面 VALIDATION 会实际跑一遍）：
    1. 映射的**值**必须都在 categorize.CATEGORIES 里。
       写进一个不存在的分类名不会报错——它只是让那笔交易从所有分类统计里
       消失，报表总额无声地少一块。凭眼睛看是发现不了的。
    2. 查表用「字面包含」而不是等号。
       平台类目名会改版（支付宝前后改过不止一次分类体系），写死等号的话
       改版当天整张表失效，而且失效得非常安静。用包含的话，
       「餐饮美食」「餐饮」都能命中，新名字只要还带着那个词就仍然认得。
"""

